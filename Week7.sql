SELECT DISTINCT P.PNAME
FROM PART P
JOIN CATALOG C
ON P.PID = C.PID;

SELECT S.SNAME
FROM SUPPLIER S
WHERE NOT EXISTS (
    SELECT *
    FROM PART P
    WHERE NOT EXISTS (
        SELECT *
        FROM CATALOG C
        WHERE C.SID = S.SID
        AND C.PID = P.PID
    )
);

SELECT S.SNAME
FROM SUPPLIER S
WHERE NOT EXISTS ( 
    SELECT * 
    FROM PART P 
    WHERE P.COLOR='RED'	
    AND NOT EXISTS ( 
         SELECT * FROM CATALOG C 
         WHERE C.SID = S.SID 
         AND C.PID = P.PID
	)
);

SELECT P.PNAME 
FROM PART P
JOIN CATALOG C
ON P.PID = C.PID
JOIN SUPPLIER S
ON C.SID = S.SID
WHERE S.SNAME = 'Acme Widget'
AND P.PID NOT IN (
    SELECT C2.PID
    FROM CATALOG C2
    WHERE C2.SID NOT IN (
        SELECT SID
        FROM SUPPLIER
        WHERE SNAME = 'Acme Widget'
    )
);

SELECT DISTINCT C1.SID
FROM CATALOG C1
WHERE C1.COST > (
    SELECT AVG(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = C1.PID
);

SELECT P.PID, S.SNAME
FROM PART P
JOIN CATALOG C
ON P.PID = C.PID
JOIN SUPPLIER S
ON C.SID = S.SID
WHERE C.COST = (
    SELECT MAX(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = P.PID
);
