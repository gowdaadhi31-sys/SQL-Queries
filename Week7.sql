CREATE DATABASE 1BM26CS480_SUPPLIER;
USE 1BM26CS480_SUPPLIER;

CREATE TABLE Supplier (
    SID INT PRIMARY KEY,
    SName VARCHAR(100) NOT NULL,
    City VARCHAR(100) NOT NULL
);

CREATE TABLE Part (
    PID INT PRIMARY KEY,
    PName VARCHAR(100) NOT NULL,
    Color VARCHAR(50) NOT NULL
);

CREATE TABLE Catalog (
    SID INT NOT NULL,
    PID INT NOT NULL,
    Cost DECIMAL(12,2) NOT NULL
        CHECK (Cost >= 0),

    PRIMARY KEY (SID, PID),

    FOREIGN KEY (SID)
        REFERENCES Supplier(SID)
        ON DELETE RESTRICT,
        
    FOREIGN KEY (PID)
        REFERENCES Part(PID)
        ON DELETE RESTRICT 
);

