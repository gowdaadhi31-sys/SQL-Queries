USE 1BM26CS480_SUPPLIER;

SELECT P.PNAME, S.SNAME, C.COST
FROM SUPPLIER S, PART P, CATALOG C
WHERE S.SID = C.SID
AND P.PID = C.PID
AND C.COST = (
    SELECT MAX(COST)
    FROM CATALOG
);

SELECT S.SNAME
FROM SUPPLIER S
WHERE NOT EXISTS (
    SELECT *
    FROM CATALOG C, PART P
    WHERE C.PID = P.PID
    AND C.SID = S.SID
    AND P.COLOR = 'Red'
);

SELECT S.SNAME, SUM(C.COST) AS TOTAL_VALUE
FROM SUPPLIER S
LEFT JOIN CATALOG C
ON S.SID = C.SID
GROUP BY S.SID, S.SNAME;

SELECT S.SNAME
FROM SUPPLIER S
JOIN CATALOG C
ON S.SID = C.SID
WHERE C.COST < 20
GROUP BY S.SID, S.SNAME
HAVING COUNT(DISTINCT C.PID) >= 2;

SELECT P.PNAME, S.SNAME, C.COST
FROM SUPPLIER S
JOIN CATALOG C
ON S.SID = C.SID
JOIN PART P
ON P.PID = C.PID
WHERE C.COST = (
    SELECT MIN(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = C.PID
);

CREATE VIEW MOST_EXPENSIVE_SUPPLIER AS
SELECT P.PNAME, S.SNAME, C.COST
FROM SUPPLIER S
JOIN CATALOG C
ON S.SID = C.SID
JOIN PART P
ON P.PID = C.PID
WHERE C.COST = (
    SELECT MAX(C2.COST)
    FROM CATALOG C2
    WHERE C2.PID = C.PID
);
SELECT * FROM MOST_EXPENSIVE_SUPPLIER;